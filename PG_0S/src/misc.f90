    U(II) = UN
    ! U(II) AND UN ARE UNIFORM ON [0,1)
    ! VNI IS UNIFORM ON [-1,1)
    VNI = UN + UN -1.
    II = II-1
    IF (II .EQ. 0)II = 17
    JJ = JJ-1
    IF (JJ .EQ. 0)JJ = 17
    ! INT(UN(II)*128) IN RANGE [0,127],  J IS IN RANGE [1,64]
