    ! PICK SIGN AS VNI IS POSITIVE OR NEGATIVE
    DRNOR = VNI*V(J+1)
    IF (ABS(DRNOR) .LE. V(J)) RETURN

    ! SLOW PART; AA IS A*F(0)

    X = (ABS(DRNOR)-V(J))/(V(J+1)-V(J))
    ! Y IS UNIFORM ON [0,1)
    Y = U(II)-U(JJ)
    IF (Y .LT. 0.0D0) Y = Y+1.
    U(II) = Y
    II = II-1
    IF (II .EQ. 0) II = 17
    JJ = JJ-1
    IF (JJ .EQ. 0) JJ = 17

    S = X+Y
    IF (S .GT. C2) THEN
      DRNOR = SIGN(B-B*X, DRNOR)
      RETURN
    ENDIF
    IF (S .LE. C1) RETURN
    IF (Y .GT. C-AA*EXP(-.5D0*(B-B*X)**2)) THEN
      DRNOR = SIGN(B-B*X, DRNOR)
      RETURN
    ENDIF
    IF (EXP(-.5D0*V(J+1)**2)+Y*PC/V(J+1) .LE. EXP(-.5D0*DRNOR**2)) RETURN

    ! TAIL PART; .36010157... IS 1.0D0/XN
    ! Y IS UNIFORM ON [0,1)
2222 Y = U(II)-U(JJ)
    IF (Y .LE. 0.0D0) Y = Y+1.
    U(II) = Y
    II = II-1
    IF (II .EQ. 0)II = 17
    JJ = JJ-1
    IF (JJ .EQ. 0)JJ = 17

    X = 0.360101571301190680192994239651D+00*LOG(Y)
    ! Y IS UNIFORM ON [0,1)
    Y = U(II)-U(JJ)
    IF (Y .LE. 0.0D0) Y = Y+1.
    U(II) = Y
    II = II-1
    IF (II .EQ. 0)II = 17
    JJ = JJ-1
    IF (JJ .EQ. 0)JJ = 17
    IF (-2.0D0*LOG(Y) .LE. X**2) GOTO 2222
    DRNOR = SIGN(XN-X, DRNOR)
    RETURN

